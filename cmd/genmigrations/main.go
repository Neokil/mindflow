// Command genmigrations discovers and links domain-owned embedded Goose packages.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

var (
	errRegistryStale  = errors.New("migration catalog is stale; run make generate")
	errInvalidPackage = errors.New("invalid migration package")
)

func main() {
	check := flag.Bool("check", false, "check the catalog without writing it")
	flag.Parse()
	err := run(*check)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(check bool) error {
	root, err := moduleRoot()
	if err != nil {
		return err
	}
	source, err := catalogSource(root)
	if err != nil {
		return err
	}
	target := filepath.Join(root, "internal", "mindflow", "storage", "migrations_generated.go")
	if check {
		current, readErr := os.ReadFile(target) //nolint:gosec // G304: target is the fixed catalog path under the discovered Go module.
		if readErr != nil {
			return fmt.Errorf("read migration catalog: %w", readErr)
		}
		if !bytes.Equal(current, source) {
			return errRegistryStale
		}

		return nil
	}
	err = os.WriteFile(target, source, generatedFileMode)
	if err != nil {
		return fmt.Errorf("write migration catalog: %w", err)
	}

	return nil
}

func moduleRoot() (string, error) {
	directory, err := os.Getwd()
	if err != nil {
		return "", fmt.Errorf("get working directory: %w", err)
	}
	for {
		_, statErr := os.Stat(filepath.Join(directory, "go.mod"))
		if statErr == nil {
			return directory, nil
		}
		if !errors.Is(statErr, os.ErrNotExist) {
			return "", fmt.Errorf("locate module: %w", statErr)
		}
		parent := filepath.Dir(directory)
		if parent == directory {
			return "", fs.ErrNotExist
		}
		directory = parent
	}
}

type migrationPackage struct{ name, path string }

func discover(root string) ([]migrationPackage, error) {
	internal := filepath.Join(root, "internal")
	packages := []migrationPackage{}
	err := filepath.WalkDir(internal, func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if !entry.IsDir() || entry.Name() != "migrations" || filepath.Base(filepath.Dir(path)) != "storage" {
			return nil
		}
		relative, relErr := filepath.Rel(root, path)
		if relErr != nil {
			return fmt.Errorf("resolve migration package path: %w", relErr)
		}
		domain, relErr := filepath.Rel(internal, filepath.Dir(filepath.Dir(path)))
		if relErr != nil {
			return fmt.Errorf("resolve migration package path: %w", relErr)
		}
		name := strings.ReplaceAll(filepath.ToSlash(domain), "/", "_")
		if !regexp.MustCompile(`^[a-z][a-z0-9_]*$`).MatchString(name) {
			return fmt.Errorf("%w: %s", errInvalidPackage, relative)
		}
		packages = append(packages, migrationPackage{name: name, path: filepath.ToSlash(relative)})

		return filepath.SkipDir
	})
	if err != nil {
		return nil, fmt.Errorf("discover domain migrations: %w", err)
	}
	sort.Slice(packages, func(left, right int) bool { return packages[left].name < packages[right].name })
	seen := map[string]bool{}
	for _, candidate := range packages {
		if seen[candidate.name] {
			return nil, fmt.Errorf("%w: duplicate name %s", errInvalidPackage, candidate.name)
		}
		seen[candidate.name] = true
	}

	return packages, nil
}

func catalogSource(root string) ([]byte, error) {
	packages, err := discover(root)
	if err != nil {
		return nil, err
	}
	module, err := os.ReadFile(filepath.Join(root, "go.mod")) //nolint:gosec // G304: root comes from locating this module, not command-line path input.
	if err != nil {
		return nil, fmt.Errorf("read module: %w", err)
	}
	fields := strings.Fields(string(module))
	if len(fields) < 2 || fields[0] != "module" {
		return nil, errInvalidPackage
	}
	var source strings.Builder
	source.WriteString("// Code generated by genmigrations. DO NOT EDIT.\n\npackage storage\nimport(\n")
	for _, candidate := range packages {
		fmt.Fprintf(&source, "%smigrations %q\n", candidate.name, fields[1]+"/"+candidate.path)
	}
	source.WriteString(")\nfunc discoveredMigrations()[]domainMigrations{return []domainMigrations{\n")
	for _, candidate := range packages {
		fmt.Fprintf(&source, "{name:%q,files:%smigrations.Files(),dependencies:%smigrations.Dependencies()},\n", candidate.name, candidate.name, candidate.name)
	}
	source.WriteString("}}\n")
	generated, err := format.Source([]byte(source.String()))
	if err != nil {
		return nil, fmt.Errorf("format migration catalog: %w", err)
	}

	return generated, nil
}

const generatedFileMode = 0o600
